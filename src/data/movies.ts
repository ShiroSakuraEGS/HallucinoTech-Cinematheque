export const MOVIE_LIST: MovieInfo[] = Object.values(MOVIES);

/**
 * Deterministically match any QR code string to one of the 4 movies.
 */
export function matchMovieFromQR(qrData: string): MovieInfo {
  const normalized = qrData.trim().toLowerCase();

  // 1. Direct keywords
  if (normalized.includes('喜') || normalized.includes('囍') || normalized.includes('wedding') || normalized.includes('marry') || normalized.includes('冥婚')) {
    return MOVIES.xibuxi;
  }
  if (normalized.includes('籤') || normalized.includes('签') || normalized.includes('cyber') || normalized.includes('divin') || normalized.includes('天母') || normalized.includes('蛆')) {
    return MOVIES.dianziqian;
  }
  if (normalized.includes('氛') || normalized.includes('編程') || normalized.includes('编程') || normalized.includes('code') || normalized.includes('vibe') || normalized.includes('煙花') || normalized.includes('烟花')) {
    return MOVIES.fenweibiancheng;
  }
  if (normalized.includes('情') || normalized.includes('館') || normalized.includes('馆') || normalized.includes('love') || normalized.includes('cybrothel') || normalized.includes('berlin') || normalized.includes('vr')) {
    return MOVIES.qingrenguan;
  }

  // 2. Hash-based matching for any arbitrary QR code (URLs, random numbers, Wi-Fi strings, etc.)
  let hash = 0;
  for (let i = 0; i < qrData.length; i++) {
    hash = (hash << 5) - hash + qrData.charCodeAt(i);
    hash |= 0;
  }
  const movieKeys: MovieId[] = ['xibuxi', 'dianziqian', 'fenweibiancheng', 'qingrenguan'];
  const index = Math.abs(hash) % movieKeys.length;
  return MOVIES[movieKeys[index]];
}
